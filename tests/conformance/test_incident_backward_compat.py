def _discover_golden_bundles() -> list[str]:
    """Return the sorted names of all golden bundle directories.

    A golden bundle directory is any immediate subdirectory of
    ``golden-bundles/`` that contains an ``acef-manifest.json``. Sorted for
    byte-stable, order-independent parametrization.
    """
    if not GOLDEN_BUNDLES_DIR.is_dir():
        return []
    names = [
        child.name
        for child in GOLDEN_BUNDLES_DIR.iterdir()
        if child.is_dir() and (child / "acef-manifest.json").is_file()
    ]
    return sorted(names)


def _load_manifest(bundle_name: str) -> dict[str, Any]:
    manifest_path = GOLDEN_BUNDLES_DIR / bundle_name / "acef-manifest.json"
    data = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert isinstance(data, dict)
    return data


def _bundle_core_version(bundle_name: str) -> str:
    manifest = _load_manifest(bundle_name)
    versioning = manifest.get("versioning")
    if not isinstance(versioning, dict):
        return ""
    cv = versioning.get("core_version", "")
    return cv if isinstance(cv, str) else ""


def _bundle_profiles(bundle_name: str) -> list[str]:
    manifest = _load_manifest(bundle_name)
    return [p["profile_id"] for p in manifest.get("profiles", [])]


def _load_fixture(bundle_name: str) -> dict[str, Any]:
    fixture_path = GOLDEN_BUNDLES_DIR / f"{bundle_name}.acef-assessment.json"
    return json.loads(fixture_path.read_text(encoding="utf-8"))


def _record_types(bundle_name: str) -> set[str]:
    """Record types declared in a golden bundle's manifest record_files."""
    manifest = _load_manifest(bundle_name)
    rec_files = manifest.get("record_files", [])
    return {rf["record_type"] for rf in rec_files if isinstance(rf, dict) and "record_type" in rf}


def _discover_v1_0_golden_bundles() -> list[str]:
    """Sorted golden bundles whose manifest declares ``core_version: 1.0.0``.

    The v1.0-compat parametrization runs ONLY over these — we never assume all
    goldens are 1.0.0. A non-1.0.0 golden (e.g. a future v1.1 fixture placed
    here) is excluded from the v1.0 backward-compat surface by design.
    """
    return [name for name in _discover_golden_bundles() if _bundle_core_version(name) == V1_0_CORE_VERSION]


GOLDEN_BUNDLE_NAMES: list[str] = _discover_golden_bundles()
V1_0_GOLDEN_BUNDLE_NAMES: list[str] = _discover_v1_0_golden_bundles()


def _all_diagnostic_codes(assessment: Any) -> list[str]:
    """Collect every diagnostic ``code`` surfaced by an assessment.

    The validation engine flushes ALL phase diagnostics — schema, integrity,
    reference, cross-record, v1.1 rules, AND the RFC-0002 incident rules — into
    ``assessment.structural_errors`` as dicts carrying a ``code`` key.
    """
    codes: list[str] = []
    for diag in assessment.structural_errors:
        code = diag.get("code") if isinstance(diag, dict) else None
        if isinstance(code, str):
            codes.append(code)
    return codes


# ---------------------------------------------------------------------------
# Deterministic surface serializers (drive BOTH generation and assertion)
# ---------------------------------------------------------------------------


def _normalize_diagnostic(diag: dict[str, Any]) -> dict[str, str]:
    """Project a structural diagnostic onto its compatibility-relevant fields.

    The full backward-compat surface for a structural diagnostic is its
    ``code``, ``severity``, ``category``, ``path``, and ``message`` — a change
    to ANY of these is a backward-compat regression and must fail. Missing
    fields normalize to the empty string so the projection is total and
    byte-stable.
    """
    return {
        "code": str(diag.get("code", "")),
        "severity": str(diag.get("severity", "")),
        "category": str(diag.get("category", "")),
        "path": str(diag.get("path", "")),
        "message": str(diag.get("message", "")),
    }


def _compute_compat_surface(bundle_name: str) -> dict[str, Any]:
    """Deterministically serialize the full backward-compat assessment surface.

    For ``bundle_name`` (a v1.0 golden), run ``validate_bundle`` at the
    fixture's ``evaluation_instant`` and return a JSON-serializable, sorted
    structure capturing everything a backward-compat regression must pin:

    * ``structural_diagnostics`` — every structural diagnostic projected onto
      (code, severity, category, path, message), sorted for determinism.
    * ``provision_outcomes`` — ``{profile_id}::{provision_id} -> outcome`` for
      every provision, sorted by key.
    * ``rule_result_counts`` — ``outcome -> count`` over all rule results,
      sorted by key.

    This is strictly the runtime surface (not the goldens' own committed
    ``.acef-assessment.json``), so a perturbation of the v1.0 validation path
    by future work flips at least one of these and fails the snapshot compare.
    """
    bundle_dir = GOLDEN_BUNDLES_DIR / bundle_name
    fixture = _load_fixture(bundle_name)
    evaluation_instant = fixture["evaluation_instant"]
    profiles = _bundle_profiles(bundle_name)

    assessment = validate_bundle(
        bundle_dir,
        profiles=profiles,
        evaluation_instant=evaluation_instant,
    )

    diagnostics = [_normalize_diagnostic(diag) for diag in assessment.structural_errors if isinstance(diag, dict)]
    # Sort by the full projected tuple so ordering is content-driven and stable.
    diagnostics.sort(key=lambda d: (d["code"], d["severity"], d["category"], d["path"], d["message"]))

    provision_outcomes: dict[str, str] = {}
    for ps in assessment.provision_summary:
        provision_outcomes[f"{ps.profile_id}::{ps.provision_id}"] = ps.provision_outcome.value

    rule_result_counts: dict[str, int] = {}
    for r in assessment.results:
        outcome = r.outcome.value
        rule_result_counts[outcome] = rule_result_counts.get(outcome, 0) + 1

    return {
        "structural_diagnostics": diagnostics,
        "provision_outcomes": dict(sorted(provision_outcomes.items())),
        "rule_result_counts": dict(sorted(rule_result_counts.items())),
    }


def _compute_all_compat_surfaces() -> dict[str, Any]:
    """The committed-snapshot mapping: ``bundle_name -> compat surface``.

    Keyed and ordered by sorted bundle name over the v1.0 goldens.
    """
    return {name: _compute_compat_surface(name) for name in sorted(V1_0_GOLDEN_BUNDLE_NAMES)}


def _iter_frozen_files() -> list[Path]:
    """Every regular file under the frozen paths, sorted by repo-relative path.

    Pure filesystem walk — NO git dependency. Sorting by the POSIX
    repo-relative path makes the listing byte-stable across platforms and runs.
    """
    files: list[Path] = []
    for frozen in FROZEN_PATHS:
        base = REPO_ROOT / frozen
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if path.is_file():
                files.append(path)
    files.sort(key=lambda p: p.relative_to(REPO_ROOT).as_posix())
    return files


def _compute_frozen_checksums() -> dict[str, str]:
    """Map every frozen-path file (repo-relative POSIX) to its SHA-256 hex.

    Deterministic and git-free: sorted keys, lowercase hex digests. This is the
    source of truth for "frozen paths byte-unchanged" in any checkout.
    """
    manifest: dict[str, str] = {}
    for path in _iter_frozen_files():
        rel = path.relative_to(REPO_ROOT).as_posix()
        manifest[rel] = hashlib.sha256(path.read_bytes()).hexdigest()
    return dict(sorted(manifest.items()))


def _serialize_fixture(payload: Any) -> str:
    """Canonical, byte-stable JSON serialization for the committed fixtures.

    Sorted keys, two-space indent, trailing newline — regenerating on an
    unchanged tree yields a byte-identical file.
    """
    return json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


