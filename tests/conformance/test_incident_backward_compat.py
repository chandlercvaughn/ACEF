"""Backward-compatibility regression — RFC-0002 (F-M4-BACKWARD-COMPAT).

Asserts VAL-COMPAT-001: every existing v1.0 golden bundle (and any
``incident_report`` golden placed under the v1.0 set) validates
**byte-identically under ``core_version: 1.0.0`` after this operation**, and
the two frozen paths (``acef-conventions/v1/`` +
``tests/conformance/golden-bundles/``) are byte-unchanged versus the
operation base state.

Why this exists
---------------
RFC-0002 adds the v1.1 incident surface: the ``incident_card`` /
``card_source`` schemas, the ACEF-081..088 error band, and the offline
incident rules in ``src/acef/validation/engine.py``. All of that is
**version-gated** on ``manifest.versioning.core_version == "1.1.0"``
(``schema_version_for_core_version`` routes 1.0.x → ``"v1"`` and the engine
only dispatches ``run_incident_rules`` when ``schema_version == "v1.1"``).

This regression proves the gate holds for the frozen v1.0 goldens with NO
git-history dependency (works in shallow CI checkouts, source archives, and
rebased trees):

1.  **No new incident code fires.** Running ``validate_bundle`` on each v1.0
    golden produces ZERO diagnostics in the reserved RFC-0002 band
    (ACEF-081..088). A v1.0 bundle must never see an incident rule.
2.  **The full backward-compat assessment surface is byte-stable AND LOSSLESS.**
    For each v1.0 golden we run ``validate_bundle`` NOW, deterministically
    serialize the *complete* compatibility-relevant assessment surface, and
    compare it byte-for-byte against a COMMITTED snapshot
    (``fixtures/v1_backward_compat_assessments.json``). The surface is three
    CANONICAL SORTED LISTS that preserve full identity — NOT reduced dicts or
    counts:

    * ``structural_diagnostics`` — every structural diagnostic projected onto
      (code, severity, category, path, message).
    * ``provision_summary`` — one entry PER provision summary, carrying its full
      identity: ``profile_id``, ``provision_id``, ``subject_scope`` (so the
      ``multi-subject-composed`` golden's repeated NIST provisions for DIFFERENT
      subjects stay distinct, never collapsed), ``outcome``, and the roll-up
      counts (``fail_count`` / ``warning_count`` / ``skipped_count``) and
      ``evidence_refs``. Keyed list, NOT a ``{profile::provision -> outcome}``
      dict (which collapsed subject-scoped duplicates and let one be
      dropped/mutated silently).
    * ``results`` — one entry PER rule result, carrying its full identity:
      ``rule_id``, ``provision_id``, ``profile_id``, ``severity``, ``outcome``,
      ``subject_scope``, ``message``, and ``evidence_refs``. A SORTED LIST, NOT
      an ``{outcome -> count}`` reduction (which let a changed rule_id / scope /
      severity / message pass as long as the counts were preserved).

    Since the operation preserves v1.0 behavior, that committed snapshot IS the
    v1.0 baseline: any FUTURE regression — a changed severity / category / path /
    message on a diagnostic, an added/removed/mutated provision summary
    (including a per-subject_scope duplicate), or a changed rule_id / scope /
    severity / message / outcome on any single rule result — flips at least one
    entry and fails this test. (This is strictly stronger than BOTH the original
    "compare error CODES only" surface AND the intermediate "outcome dict +
    per-outcome counts" surface, both of which let subject-scoped duplicates and
    per-rule identity changes pass silently.)
3.  **The frozen paths match their committed checksums.** A COMMITTED checksum
    manifest (``fixtures/v1_frozen_checksums.json``) maps every file under
    ``acef-conventions/v1/`` and ``tests/conformance/golden-bundles/`` to its
    SHA-256. The test asserts the CURRENT on-disk files match that manifest
    exactly — same file set, same hashes — the authoritative, git-free proof in
    ANY checkout (shallow / archive / no-git). The golden bundles are
    re-baselineable by the sanctioned ``--regen`` (a reviewed change such as F1
    regenerates them once the SDK stops emitting invalid bytes); ``acef-conventions/v1``
    stays byte-frozen (VAL-SCHEMA-010). Unintentional drift — an edited golden
    whose checksum fixture was not re-gen'd — fails the compare.

Snapshot provenance
-------------------
Both fixtures are generated by the deterministic helpers in this module
(``_compute_frozen_checksums`` and ``_compute_compat_surface``) and committed.
Regenerating them on an unchanged tree yields byte-identical files. To
regenerate intentionally (after a sanctioned, reviewed change), run this module
as a script::

    python -m tests.conformance.test_incident_backward_compat --regen

The committed snapshot — NOT the goldens' own ``.acef-assessment.json``
fixtures — is the source of truth for the *runtime* backward-compat surface.
The goldens' committed ``structural_errors`` carry a pre-existing divergence
from the live runtime (some fixtures list ``ACEF-032`` "provision not yet
effective" as a structural error where the current runtime instead surfaces it
as a skipped rule *result*); see ``_compute_compat_surface`` for how that is
normalized into the snapshot.

Determinism: golden bundles are discovered by sorted directory scan (no
hard-coded brittle list drives the parametrization), filtered to
``core_version == "1.0.0"``; a coverage floor asserts the known v1.0 goldens
are still present so coverage cannot silently shrink. The frozen-path walk and
every serialized surface are sorted. No wall-clock, no randomness — the fixture
``evaluation_instant`` drives every comparison.
"""

