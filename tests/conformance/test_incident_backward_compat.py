# (3) Frozen paths are byte-unchanged — committed checksum manifest (no git dep)
# ---------------------------------------------------------------------------


@pytest.mark.regression
class TestFrozenPathsByteUnchanged:
    """``acef-conventions/v1/`` + golden-bundles match the committed checksum manifest.

    The committed ``v1_frozen_checksums.json`` captures the base/pre-operation
    state of the frozen paths (the operation never touched them). The test
    asserts the CURRENT on-disk files match it exactly — same file set, same
    SHA-256 — proving "frozen paths byte-unchanged" in ANY checkout (shallow
    CI, source archive, rebased history) with NO git dependency.
    """

    def test_checksum_manifest_fixture_exists(self) -> None:
        assert FROZEN_CHECKSUMS_FIXTURE.is_file(), (
            f"Committed frozen-path checksum manifest missing: {FROZEN_CHECKSUMS_FIXTURE}. "
            "Regenerate with `python -m tests.conformance.test_incident_backward_compat --regen`."
        )

    def test_checksum_manifest_is_nonempty(self) -> None:
        manifest = json.loads(FROZEN_CHECKSUMS_FIXTURE.read_text(encoding="utf-8"))
        assert manifest, "Frozen-path checksum manifest is empty — the proof would be vacuous"

    def test_checksum_manifest_covers_both_frozen_roots(self) -> None:
        """The manifest contains files under BOTH frozen roots (no half-coverage)."""
        manifest = json.loads(FROZEN_CHECKSUMS_FIXTURE.read_text(encoding="utf-8"))
        for frozen in FROZEN_PATHS:
            prefix = f"{frozen}/"
            assert any(k.startswith(prefix) for k in manifest), (
                f"Frozen-path checksum manifest covers no files under '{frozen}' — coverage gap"
            )

    def test_current_files_match_committed_checksum_manifest(self) -> None:
        """CURRENT on-disk frozen files == committed manifest: same set, same SHA-256.

        This is the PRIMARY frozen-path proof. No git: a pure filesystem walk
        plus SHA-256 compared against the committed manifest. Works in shallow
        CI checkouts, source archives, and rebased trees.
        """
        committed: dict[str, str] = json.loads(FROZEN_CHECKSUMS_FIXTURE.read_text(encoding="utf-8"))
        current = _compute_frozen_checksums()

        committed_files = set(committed.keys())
        current_files = set(current.keys())

        added = sorted(current_files - committed_files)
        removed = sorted(committed_files - current_files)
        assert not added and not removed, (
            "Frozen-path file SET changed vs the committed manifest "
            "(FROZEN: VAL-SCHEMA-010 / VAL-REGRESSION-001): "
            f"added={added} removed={removed}"
        )

        changed = sorted(rel for rel in committed_files & current_files if committed[rel] != current[rel])
        assert not changed, (
            "Frozen-path file CONTENT changed vs the committed manifest "
            f"(FROZEN: VAL-SCHEMA-010 / VAL-REGRESSION-001): {changed}"
        )

    def test_checksum_manifest_is_deterministic_across_two_runs(self) -> None:
        """Recomputing the checksum manifest twice yields a byte-identical blob."""
        first = _serialize_fixture(_compute_frozen_checksums())
        second = _serialize_fixture(_compute_frozen_checksums())
        assert first == second, "Frozen-path checksum manifest computation is non-deterministic"

    def test_committed_manifest_blob_is_canonical(self) -> None:
        """The committed manifest is exactly the canonical serialization (regen-stable)."""
        committed_blob = FROZEN_CHECKSUMS_FIXTURE.read_text(encoding="utf-8")
        canonical_blob = _serialize_fixture(_compute_frozen_checksums())
        assert committed_blob == canonical_blob, (
            "Committed frozen-path checksum manifest is not byte-identical to its canonical "
            "regeneration on the current (unchanged) tree — regenerate the fixture."
        )

    def test_frozen_path_proof_is_git_free(self) -> None:
        """The frozen-path proof does NOT depend on git and re-baselines via ``--regen``.

        The committed checksum manifest (``v1_frozen_checksums.json``) is the
        AUTHORITATIVE, git-free, deterministic proof that the frozen paths
        (``acef-conventions/v1`` + the golden bundles) are exactly their committed
        bytes — it holds in any checkout (shallow / archive / no-git). The former
        ``git diff --stat`` cross-check against a pinned operation-base commit was
        an artifact of the (now-completed) audit-remediation operation's
        ``frozen-forever`` invariant; the golden bundles are now re-baselineable by
        the sanctioned ``--regen`` (e.g. F1 regenerated them once the SDK stopped
        auto-emitting a schema-invalid ``audit_trail[0].actor_ref``), so anchoring
        to that stale commit is obsolete. Unintentional drift is still caught here:
        an edited golden whose checksum fixture was NOT re-gen'd fails this compare.
        """
        committed: dict[str, str] = json.loads(FROZEN_CHECKSUMS_FIXTURE.read_text(encoding="utf-8"))
        current = _compute_frozen_checksums()
        assert committed == current, "Frozen-path checksum proof must hold (re-run --regen after a sanctioned change)"


