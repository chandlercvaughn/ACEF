@pytest.mark.regression
class TestBackwardCompatAssessmentSnapshot:
    """Runtime backward-compat surface == the committed byte-identical baseline.

    The committed ``v1_backward_compat_assessments.json`` snapshot is the
    byte-identical-compat baseline for the runtime: it pins, per v1.0 golden,
    the full structural-diagnostic surface (code, severity, category, path,
    message), the provision outcomes, and the per-outcome rule-result counts.
    Because the operation preserves v1.0 behavior, this snapshot == the v1.0
    baseline; committing it makes ANY future regression — a changed severity /
    category / path / message, an added or removed diagnostic, a drifted
    outcome or count — fail this test.
    """

    def test_snapshot_fixture_exists(self) -> None:
        assert COMPAT_ASSESSMENTS_FIXTURE.is_file(), (
            f"Committed backward-compat assessment snapshot missing: {COMPAT_ASSESSMENTS_FIXTURE}. "
            "Regenerate with `python -m tests.conformance.test_incident_backward_compat --regen`."
        )

    def test_snapshot_covers_exactly_the_v1_0_goldens(self) -> None:
        snapshot = json.loads(COMPAT_ASSESSMENTS_FIXTURE.read_text(encoding="utf-8"))
        snapshot_bundles = set(snapshot.keys())
        discovered = set(V1_0_GOLDEN_BUNDLE_NAMES)
        assert snapshot_bundles == discovered, (
            "Committed snapshot bundle set drifted from the discovered v1.0 goldens: "
            f"missing_from_snapshot={sorted(discovered - snapshot_bundles)} "
            f"stale_in_snapshot={sorted(snapshot_bundles - discovered)}"
        )

    def test_snapshot_covers_coverage_floor(self) -> None:
        snapshot = json.loads(COMPAT_ASSESSMENTS_FIXTURE.read_text(encoding="utf-8"))
        missing = KNOWN_V1_0_GOLDEN_BUNDLES - set(snapshot.keys())
        assert not missing, f"Committed snapshot is missing known v1.0 golden(s): {sorted(missing)}"

    @pytest.mark.parametrize("bundle_name", V1_0_GOLDEN_BUNDLE_NAMES)
    def test_runtime_surface_matches_snapshot(self, bundle_name: str) -> None:
        """The runtime backward-compat surface equals the committed snapshot.

        Byte-for-byte over the canonically-serialized per-bundle surface — far
        stronger than comparing only error codes (which let severity /
        category / path / message changes and added/removed diagnostics pass
        silently).
        """
        snapshot = json.loads(COMPAT_ASSESSMENTS_FIXTURE.read_text(encoding="utf-8"))
        assert bundle_name in snapshot, f"[{bundle_name}] not present in committed snapshot — regenerate the fixture"

        runtime_surface = _compute_compat_surface(bundle_name)
        expected_surface = snapshot[bundle_name]

        runtime_blob = _serialize_fixture(runtime_surface)
        expected_blob = _serialize_fixture(expected_surface)
        assert runtime_blob == expected_blob, (
            f"[{bundle_name}] backward-compat assessment surface drifted vs the committed "
            f"byte-identical baseline. A severity/category/path/message change, an "
            f"added/removed diagnostic, or a drifted outcome/count regressed v1.0 behavior.\n"
            f"--- runtime ---\n{runtime_blob}\n--- expected ---\n{expected_blob}"
        )

    @pytest.mark.parametrize("bundle_name", V1_0_GOLDEN_BUNDLE_NAMES)
    def test_snapshot_has_no_incident_band_code(self, bundle_name: str) -> None:
        """No structural diagnostic in the committed snapshot is an 08x incident code."""
        snapshot = json.loads(COMPAT_ASSESSMENTS_FIXTURE.read_text(encoding="utf-8"))
        diags = snapshot[bundle_name]["structural_diagnostics"]
        incident_codes = sorted({d["code"] for d in diags if INCIDENT_CODE_RE.match(d["code"])})
        assert not incident_codes, (
            f"[{bundle_name}] committed snapshot contains RFC-0002 incident-band code(s) "
            f"on a v1.0 bundle: {incident_codes}"
        )

    @pytest.mark.parametrize("bundle_name", V1_0_GOLDEN_BUNDLE_NAMES)
    def test_runtime_surface_is_deterministic_across_two_runs(self, bundle_name: str) -> None:
        """The serialized runtime surface is byte-identical across two computations."""
        first = _serialize_fixture(_compute_compat_surface(bundle_name))
        second = _serialize_fixture(_compute_compat_surface(bundle_name))
        assert first == second, f"[{bundle_name}] backward-compat surface is non-deterministic across runs"

    @pytest.mark.parametrize("bundle_name", V1_0_GOLDEN_BUNDLE_NAMES)
    def test_golden_loads_clean(self, bundle_name: str) -> None:
        """Each v1.0 golden still loads without error after the operation."""
        bundle_dir = GOLDEN_BUNDLES_DIR / bundle_name
        pkg = load(str(bundle_dir))
        assert pkg is not None
        assert len(pkg.records) > 0, f"[{bundle_name}] expected at least one record"


