@pytest.mark.regression
class TestNoIncidentCodeFiresOnV10:
    """The RFC-0002 incident band never fires on a v1.0 (core_version 1.0.0) bundle."""

    @pytest.mark.parametrize("bundle_name", V1_0_GOLDEN_BUNDLE_NAMES)
    def test_no_incident_code_in_diagnostics(self, bundle_name: str) -> None:
        """Validation of a v1.0 golden surfaces zero ACEF-081..088 diagnostics.

        This applies uniformly to EVERY v1.0 golden — including one that carries
        an ``incident_report`` record. A v1.0 ``incident_report`` is a normal
        v1.0 case (the v1.1 incident rules are version-gated and must not fire),
        so it is VALIDATED here, never blanket-rejected.
        """
        bundle_dir = GOLDEN_BUNDLES_DIR / bundle_name
        fixture = _load_fixture(bundle_name)
        evaluation_instant = fixture["evaluation_instant"]
        profiles = _bundle_profiles(bundle_name)

        assessment = validate_bundle(
            bundle_dir,
            profiles=profiles,
            evaluation_instant=evaluation_instant,
        )

        codes = _all_diagnostic_codes(assessment)
        incident_codes = [c for c in codes if INCIDENT_CODE_RE.match(c)]
        assert not incident_codes, (
            f"[{bundle_name}] RFC-0002 incident code(s) fired on a v1.0 bundle "
            f"(must be byte-equivalent-absent for core_version 1.0.0): {incident_codes}. "
            f"All diagnostic codes: {codes}"
        )

    def test_v1_0_incident_report_golden_validates_as_normal_v1_0(self) -> None:
        """If a v1.0 golden carries an ``incident_report``, it validates as v1.0.

        VAL-COMPAT-001 names ``incident_report`` goldens explicitly. The frozen
        v1.0 set currently carries none, so this is a no-op TODAY; but the
        contract is documented and enforced: were one added (now or later), it
        is a legitimate v1.0 case — validated with zero ACEF-08x firing — and
        must NOT be blanket-rejected. (This replaces the prior blanket
        ``"incident_report" not in record_types`` forbid, which would have
        rejected a legitimate v1.0 ``incident_report`` golden.)
        """
        incident_report_v1_0 = [name for name in V1_0_GOLDEN_BUNDLE_NAMES if "incident_report" in _record_types(name)]
        for bundle_name in incident_report_v1_0:
            bundle_dir = GOLDEN_BUNDLES_DIR / bundle_name
            fixture = _load_fixture(bundle_name)
            assessment = validate_bundle(
                bundle_dir,
                profiles=_bundle_profiles(bundle_name),
                evaluation_instant=fixture["evaluation_instant"],
            )
            incident_codes = [c for c in _all_diagnostic_codes(assessment) if INCIDENT_CODE_RE.match(c)]
            assert not incident_codes, (
                f"[{bundle_name}] v1.0 incident_report golden tripped a v1.1-gated incident "
                f"code (must validate as a normal v1.0 case): {incident_codes}"
            )


