            incident_codes = [c for c in _all_diagnostic_codes(assessment) if INCIDENT_CODE_RE.match(c)]
            assert not incident_codes, (
                f"[{bundle_name}] v1.0 incident_report golden tripped a v1.1-gated incident "
                f"code (must validate as a normal v1.0 case): {incident_codes}"
            )


