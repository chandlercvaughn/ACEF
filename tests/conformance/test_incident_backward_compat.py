def _regenerate_fixtures() -> list[Path]:
    """Write both committed fixtures from the current (unchanged) tree.

    Deterministic: same tree → byte-identical files. Returns the written paths.
    """
    FIXTURES_DIR.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    checksum_blob = _serialize_fixture(_compute_frozen_checksums())
    FROZEN_CHECKSUMS_FIXTURE.write_text(checksum_blob, encoding="utf-8")
    written.append(FROZEN_CHECKSUMS_FIXTURE)

    surfaces_blob = _serialize_fixture(_compute_all_compat_surfaces())
    COMPAT_ASSESSMENTS_FIXTURE.write_text(surfaces_blob, encoding="utf-8")
    written.append(COMPAT_ASSESSMENTS_FIXTURE)

    return written


def _main() -> None:
    parser = argparse.ArgumentParser(description="Backward-compat fixture (re)generation.")
    parser.add_argument(
        "--regen",
        action="store_true",
        help="Regenerate the committed checksum-manifest + assessment-surface fixtures.",
    )
    args = parser.parse_args()
    if not args.regen:
        parser.error("nothing to do — pass --regen to (re)generate the committed fixtures")
    for path in _regenerate_fixtures():
        print(f"wrote {path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    _main()
